/**
 * Regenerates src/homeBannerTints.js: one dark glass tint per home banner,
 * taken from the average colour of the lower two thirds of the photo
 * (where the widgets sit) and darkened so white text stays readable.
 *
 *   node scripts/generate-banner-tints.mjs
 */
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';

// sharp kan ligge globalt (NODE_PATH) når prosjektets avhengigheter ikke er installert.
const sharp = createRequire(import.meta.url)('sharp');

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const registry = fs.readFileSync(path.join(root, 'src/homeBanners.js'), 'utf8');
// Standard på Hjem er uten bilde. Ukjente id-er får tonen til naturbildet som var standard før.
const defaultId = 'natur-innsjo-hytte-morgen';
const pairs = [...registry.matchAll(/id: '([^']+)',[\s\S]*?source: require\('\.\.\/([^']+)'\)/g)]
  .map((m) => ({ id: m[1], file: m[2] }));

/** Brightest channel a tint may have; keeps white text at good contrast. */
const MAX_CHANNEL = 78;
const DARKEN = 0.42;

const lines = [];
for (const { id, file } of pairs) {
  const img = sharp(path.join(root, file));
  const { height } = await img.metadata();
  const top = Math.round(height / 3);
  const { channels } = await img
    .extract({ left: 0, top, width: (await img.metadata()).width, height: height - top })
    .stats();
  const avg = channels.slice(0, 3).map((c) => c.mean);
  const k = Math.min(DARKEN, MAX_CHANNEL / Math.max(...avg));
  const [r, g, b] = avg.map((v) => Math.round(v * k));
  lines.push(`  '${id}': '${r}, ${g}, ${b}',`);
}

const out = `/**
 * Dark glass tint per home banner ("r, g, b"), used behind white text on
 * the home widgets. Generated by scripts/generate-banner-tints.mjs.
 */
export const HOME_BANNER_TINTS = {
${lines.join('\n')}
};

/** Warm neutral used for uploaded photos. */
export const DEFAULT_GLASS_TINT = '44, 38, 34';

/** Unknown or missing ids show the default banner, so they get its tint. */
export function glassTintForBanner(bannerId) {
  return HOME_BANNER_TINTS[bannerId] || HOME_BANNER_TINTS['${defaultId}'] || DEFAULT_GLASS_TINT;
}
`;
fs.writeFileSync(path.join(root, 'src/homeBannerTints.js'), out);
console.log(`wrote ${lines.length} tints`);
