export const COUNTRY_BY_CODE = Object.fromEntries(
  WORLD_COUNTRIES.map((c) => [c.code, c]),
);

export function countryFlag(code) {
  const c = String(code || '').toUpperCase();
  if (c.length !== 2) return '🏳️';
  try {
    return String.fromCodePoint(...[...c].map((ch) => 127397 + ch.charCodeAt(0)));
  } catch {
    return '🏳️';
  }
}

export function searchCountries(query, { region } = {}) {
  const q = String(query || '').trim().toLowerCase();
  return WORLD_COUNTRIES.filter((c) => {
    if (region && c.region !== region) return false;
    if (!q) return true;
    return c.name.toLowerCase().includes(q)
      || c.code.toLowerCase().includes(q)
      || (c.region || '').toLowerCase().includes(q);
  });
}

export function projectToMap(lat, lng, width, height) {
  const x = ((Number(lng) + 180) / 360) * width;
  const y = ((90 - Number(lat)) / 180) * height;
  return { x, y };
}
