export function getRecipeById(id, pool = NORWEGIAN_RECIPES) {
  return (pool || []).find((r) => r.id === id) || null;
}

export function searchRecipes({
  query = '',
  category = 'all',
  tag = null,
  customRecipes = [],
  catalogRecipes = [],
  builtinRecipes = NORWEGIAN_RECIPES,
  hiddenBuiltinIds = [],
} = {}) {
  const q = query.trim().toLowerCase();
  const hidden = new Set((hiddenBuiltinIds || []).map(String));
  const mine = customRecipes || [];
  const catalog = (catalogRecipes || []).filter((r) => !hidden.has(String(r.id)));
  const builtins = (builtinRecipes || []).filter((r) => !hidden.has(String(r.id)));

  // Skjul innebygde/katalog som allerede er «overstyrt» av en familie-kopi
  const overridden = new Set(
    mine
      .flatMap((r) => [r.sourceBuiltinId, r.sourceCatalogId])
      .filter(Boolean)
      .map(String),
  );
  const visibleBuiltins = builtins.filter((r) => !overridden.has(String(r.id)));
  const visibleCatalog = catalog.filter((r) => !overridden.has(String(r.id)));

  let pool;
  if (category === 'mine') pool = mine;
  else if (category === 'all') pool = [...mine, ...visibleCatalog, ...visibleBuiltins];
  else {
    pool = [...mine, ...visibleCatalog, ...visibleBuiltins].filter((r) => r.category === category);
  }

  return pool.filter((r) => {
    if (tag && r.tag !== tag) return false;
    if (!q) return true;
    return r.title.toLowerCase().includes(q)
      || (r.description || '').toLowerCase().includes(q)
      || (r.instructions || '').toLowerCase().includes(q)
      || (r.ingredients || []).some((i) => i.name.toLowerCase().includes(q));
  });
}

export function recipesForMealType(tag, pool = NORWEGIAN_RECIPES) {
  return (pool || []).filter((r) => r.tag === tag);
}
